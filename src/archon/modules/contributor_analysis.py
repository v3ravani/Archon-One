    def _report_09_risk_analysis(self):
        txt = "====================================================\n"
        txt += "           09_RISK_ANALYSIS REPORT                  \n"
        txt += "====================================================\n\n"
        
        # Abandoned files detection (no modifications since > 180 days)
        abandoned = []
        now_ts = time.time()
        for rel_name, details in self.file_owners.items():
            age_days = (now_ts - details['last_modified']) / (24 * 3600)
            if age_days > 180.0:
                abandoned.append([rel_name, f"{age_days:.1f} days ago"])
                
        # Findings for abandoned files
        if abandoned:
            self._add_finding(
                severity="Medium",
                category="Risk Analysis",
                rule="Abandoned Files",
                reason=f"Detected {len(abandoned)} files not modified in the last 180 days.",
                impact="Stale or abandoned code increases technical debt and structure rot.",
                fix="Verify if the abandoned files are still in use, otherwise archive or delete them."
            )
            
