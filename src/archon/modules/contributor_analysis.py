import os
import re
import math
import json
import time
from pathlib import Path
from datetime import datetime, timezone
from typing import Dict, Any, List, Optional, Set, Tuple
from tabulate import tabulate

import git

class ContributorAnalysisReporter:
    def __init__(self, results: Dict[str, Any], output_root: Path):
        self.results = results
        self.output_root = output_root
        self.root_path = Path(results['root_path'])
        self.scan_duration = results['scan_duration']
        self.scan_id = results.get('scan_id', 'N/A')
        
        self.findings: List[Dict[str, Any]] = []
        self.contributors: Dict[str, Dict[str, Any]] = {}
        self.file_owners: Dict[str, Dict[str, Any]] = {}
        self.commits_list: List[Dict[str, Any]] = []
        self.git_branch = "None"
        self.git_hash = "None"
        self.total_git_commits = 0
        
        self.is_git_repo = False
        
        from archon.modules.settings_manager import load_config
        self.config = load_config(self.root_path / "archon-config.json")
        
    def generate_reports(self):
        self.output_root.mkdir(parents=True, exist_ok=True)
        self._run_git_analysis()
        
        # Output matched report pairs
        self._report_02_contributor_statistics()
        self._report_03_commit_analysis()
        self._report_04_file_ownership()
        self._report_05_collaboration_analysis()
        self._report_06_knowledge_distribution()
        self._report_07_productivity_analysis()
        self._report_08_repository_activity()
        self._report_09_risk_analysis()
        self._report_10_scan_metadata()
        self._report_01_contributor_summary() # Goes last to collect findings
        
        # Generate interactive HTML report
        from archon.core.html_generator import compile_and_write_html_report
        nav = {"prev": "../03_Code_Analysis/report.html", "next": "../05_Repository_Intelligence/report.html"}
        compile_and_write_html_report(self.output_root, self.results, "Contributor Analysis (Module 04)", nav)
        
    def _get_footer(self) -> str:
        local_time = time.localtime(self.results.get('start_time', time.time()))
        timestamp_str = time.strftime("%Y-%m-%d %H:%M:%S", local_time)
        return (
            "\n\n=========================================\n"
            "Generated by Archon One Contributor Analysis\n"
            "Version: 0.1.0\n"
            f"Scan ID: {self.scan_id}\n"
            f"Repository Name: {self.root_path.name}\n"
            f"Timestamp: {timestamp_str}\n"
            "=========================================\n"
        )
        
    def _write_files(self, base_name: str, txt_content: str, json_data: Any):
        self.output_root.mkdir(parents=True, exist_ok=True)
        txt_content_with_footer = txt_content + self._get_footer()
        
        if self.config.get('output', {}).get('txt', True):
            txt_path = self.output_root / f"{base_name}.txt"
            txt_path.write_text(txt_content_with_footer, encoding='utf-8')
            
        if self.config.get('output', {}).get('json', True):
            json_path = self.output_root / f"{base_name}.json"
            json_path.write_text(json.dumps(json_data, indent=2), encoding='utf-8')
            
        if self.config.get('output', {}).get('md', True):
            md_path = self.output_root / f"{base_name}.md"
            md_content = f"# Archon One Report - {base_name.replace('_', ' ').title()}\n\n```txt\n{txt_content_with_footer}\n```\n"
            md_path.write_text(md_content, encoding='utf-8')
        
    def _add_finding(self, severity: str, category: str, rule: str, reason: str, impact: str, fix: str, contributor: str = "N/A", file: str = "N/A"):
        finding = {
            "severity": severity,
            "category": category,
            "rule": rule,
            "reason": reason,
            "impact": impact,
            "suggested_action": fix,
            "priority": "High" if severity in ("Critical", "High") else ("Medium" if severity == "Medium" else "Low"),
            "contributor": contributor,
            "file": file,
            "recommendation": fix
        }
        self.findings.append(finding)
        
    def _run_git_analysis(self):
        try:
            repo = git.Repo(self.root_path, search_parent_directories=True)
            self.is_git_repo = True
            self.git_branch = repo.active_branch.name
            self.git_hash = repo.head.commit.hexsha
            commits = list(repo.iter_commits())
            self.total_git_commits = len(commits)
        except Exception as e:
            self.results['warnings'].append({'message': f"Not a Git repository or failed to read history: {e}"})
            return
            
        # Parse commits
        for c in commits:
            author_email = c.author.email or "unknown"
            author_name = c.author.name or "Unknown"
            authored_dt = c.authored_datetime
            message = c.message or ""
            is_merge = len(c.parents) > 1
            
            # Commit metadata
            c_info = {
                'hash': c.hexsha,
                'author': author_name,
                'email': author_email,
                'date': authored_dt.isoformat(),
                'timestamp': authored_dt.timestamp(),
                'message': message,
                'is_merge': is_merge,
                'insertions': 0,
                'deletions': 0,
                'files_changed': []
            }
            
            try:
                stats = c.stats.files
                for filename, f_stat in stats.items():
                    # Keep relative paths
                    rel_name = filename.replace('\\', '/')
                    c_info['insertions'] += f_stat.get('insertions', 0)
                    c_info['deletions'] += f_stat.get('deletions', 0)
                    c_info['files_changed'].append(rel_name)
                    
                    # Track file ownership metrics
                    if rel_name not in self.file_owners:
                        self.file_owners[rel_name] = {
                            'file': rel_name,
                            'total_commits': 0,
                            'insertions': 0,
                            'deletions': 0,
                            'contributors': {},
                            'last_modified': authored_dt.timestamp(),
                            'last_modifier': author_email,
                            'creation_date': authored_dt.timestamp()
                        }
                        
                    f_owner = self.file_owners[rel_name]
                    f_owner['total_commits'] += 1
                    f_owner['insertions'] += f_stat.get('insertions', 0)
                    f_owner['deletions'] += f_stat.get('deletions', 0)
                    
                    if author_email not in f_owner['contributors']:
                        f_owner['contributors'][author_email] = {
                            'commits': 0,
                            'insertions': 0,
                            'deletions': 0
                        }
                    f_owner['contributors'][author_email]['commits'] += 1
                    f_owner['contributors'][author_email]['insertions'] += f_stat.get('insertions', 0)
                    f_owner['contributors'][author_email]['deletions'] += f_stat.get('deletions', 0)
                    
                    if authored_dt.timestamp() > f_owner['last_modified']:
                        f_owner['last_modified'] = authored_dt.timestamp()
                        f_owner['last_modifier'] = author_email
                    if authored_dt.timestamp() < f_owner['creation_date']:
                        f_owner['creation_date'] = authored_dt.timestamp()
            except Exception:
                pass
                
            self.commits_list.append(c_info)
            
            # Track contributor metrics
            if author_email not in self.contributors:
                self.contributors[author_email] = {
                    'name': author_name,
                    'email': author_email,
                    'commits': [],
                    'merges': 0,
                    'insertions': 0,
                    'deletions': 0,
                    'files_created': 0,
                    'files_modified': set(),
                    'active_days': set(),
                    'streaks': 0,
                    'tenure_days': 0
                }
                
            contrib = self.contributors[author_email]
            contrib['commits'].append(c_info)
            if is_merge:
                contrib['merges'] += 1
            contrib['insertions'] += c_info['insertions']
            contrib['deletions'] += c_info['deletions']
            contrib['files_modified'].update(c_info['files_changed'])
            # Track active days
            day_str = authored_dt.strftime('%Y-%m-%d')
            contrib['active_days'].add(day_str)
            
        # Calculate streaks and tenure for contributors
        for email, contrib in self.contributors.items():
            sorted_dates = sorted(list(contrib['active_days']))
            contrib['first_commit'] = sorted_dates[0] if sorted_dates else "N/A"
            contrib['latest_commit'] = sorted_dates[-1] if sorted_dates else "N/A"
            
            # Streaks
            max_streak = 0
            curr_streak = 0
            prev_date = None
            for date_str in sorted_dates:
                curr_date = datetime.strptime(date_str, '%Y-%m-%d')
                if prev_date is None:
                    curr_streak = 1
                else:
                    diff = (curr_date - prev_date).days
                    if diff == 1:
                        curr_streak += 1
                    elif diff > 1:
                        if curr_streak > max_streak:
                            max_streak = curr_streak
                        curr_streak = 1
                prev_date = curr_date
            if curr_streak > max_streak:
                max_streak = curr_streak
            contrib['streaks'] = max_streak
            
            # Tenure
            if sorted_dates:
                t_diff = (datetime.strptime(sorted_dates[-1], '%Y-%m-%d') - datetime.strptime(sorted_dates[0], '%Y-%m-%d')).days
                contrib['tenure_days'] = max(1, t_diff)
            else:
                contrib['tenure_days'] = 1
                
        # Resolve class / LOC outputs of Module 01 and 03
        self._cross_reference_modules()
        
    def _cross_reference_modules(self):
        metrics_folder = self.output_root.parent / "01_metrics"
        analysis_folder = self.output_root.parent / "03_Code_Analysis"
        
        file_sizes = {}
        file_complexities = {}
        
        if metrics_folder.exists():
            p = metrics_folder / "02_file_metrics.json"
            if p.exists():
                try:
                    data = json.loads(p.read_text(encoding='utf-8'))
                    for item in data.get('scanned_files_metrics', []):
                        if 'file' in item:
                            # Normalize relative path
                            f_path = item['file'].replace('\\', '/')
                            file_sizes[f_path] = item.get('physical_loc', item.get('loc', 0))
                except Exception:
                    pass
                    
        if analysis_folder.exists():
            p = analysis_folder / "02_complexity_analysis.json"
            if p.exists():
                try:
                    data = json.loads(p.read_text(encoding='utf-8'))
                    fc = data.get('file_complexities', [])
                    for item in fc:
                        if isinstance(item, dict) and 'file' in item:
                            f_path = item['file'].replace('\\', '/')
                            file_complexities[f_path] = item.get('cyclomatic', 0)
                        elif isinstance(item, list) and len(item) > 0:
                            f_path = item[0].replace('\\', '/')
                            file_complexities[f_path] = item[1]
                except Exception:
                    pass
                    
        # Link sizes and complexities into file ownership mapping
        for f_path, owner_info in self.file_owners.items():
            owner_info['size_loc'] = file_sizes.get(f_path, 0)
            owner_info['complexity'] = file_complexities.get(f_path, 0)
            
    def _report_01_contributor_summary(self):
        txt = "====================================================\n"
        txt += "           01_CONTRIBUTOR_SUMMARY REPORT            \n"
        txt += "====================================================\n\n"
        
        if not self.is_git_repo:
            txt += "No Git repository found. Summary empty.\n"
            self._write_files("01_contributor_summary", txt, {})
            return
            
        total_contributors = len(self.contributors)
        total_commits = len(self.commits_list)
        avg_commits = total_commits / max(1, total_contributors)
        
        # Calculate Bus Factor
        # Order contributors by file ownership count
        owner_counts = {}
        for f, details in self.file_owners.items():
            # Find primary owner
            contribs = details['contributors']
            if contribs:
                primary = max(contribs.keys(), key=lambda k: contribs[k]['insertions'])
                owner_counts[primary] = owner_counts.get(primary, 0) + 1
                
        sorted_owners = sorted(owner_counts.items(), key=lambda x: x[1], reverse=True)
        total_files = len(self.file_owners)
        
        accumulated_files = 0
        bus_factor = 0
        for owner, count in sorted_owners:
            accumulated_files += count
            bus_factor += 1
            if accumulated_files > total_files / 2.0:
                break
                
        # Risk findings for Bus Factor
        if bus_factor <= 1:
            self._add_finding(
                severity="High",
                category="Risk Analysis",
                rule="Low Bus Factor",
                reason=f"The project has a Bus Factor of {bus_factor}.",
                impact="If the primary developer leaves, more than 50% of the files will be without active ownership.",
                fix="Distribute knowledge across the team by pairing on core modules."
            )
            
        txt += f"Total Contributors:          {total_contributors}\n"
        txt += f"Total Git Commits:           {total_commits}\n"
        txt += f"Average Commits/Contributor: {avg_commits:.2f}\n"
        txt += f"Repository Bus Factor:       {bus_factor}\n\n"
        
        # Table of Top Owners
        txt += "TOP REPOSITORY OWNERS:\n"
        owners_table = []
        for owner, count in sorted_owners[:5]:
            pct = (count / max(1, total_files)) * 100
            name = self.contributors.get(owner, {}).get('name', owner)
            owners_table.append([name, owner, count, f"{pct:.1f}%"])
            
        txt += tabulate(owners_table, headers=["Name", "Email Address", "Files Owned", "Ownership %"], tablefmt="grid") + "\n"
        
        json_data = {
            "total_contributors": total_contributors,
            "total_commits": total_commits,
            "average_commits_per_contributor": round(avg_commits, 2),
            "bus_factor": bus_factor,
            "top_owners": owners_table
        }
        self._write_files("01_contributor_summary", txt, json_data)
        
