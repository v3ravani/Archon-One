        txt += "           09_REPOSITORY_INSIGHTS REPORT            \n"
        txt += "====================================================\n\n"
        
        txt += "EXECUTIVE SUMMARY:\n"
        txt += "  The repository scan has been completed. Quality metrics, code smells, ownership,\n"
